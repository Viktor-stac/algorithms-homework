import numpy as np


def tridiagonalize_householder(A):
    """
    Приводит симметричную матрицу A к трехдиагональному виду
    с использованием преобразований Хаусхолдера.
    """
    n = A.shape[0]
    A = A.copy().astype(float)

    Q = np.eye(n)

    # Проходим по столбцам от 0 до n-3 (последние 2 столбца трогать не нужно)
    for k in range(n - 2):
        # 1) Берем элементы k-го столбца строго ниже главной диагонали
        x = A[k + 1:, k]

        # Вычисляем евклидову норму вектора x
        norm_x = np.linalg.norm(x)

        # Если вектор уже нулевой, пропускаем итерацию (там уже нули)
        if norm_x == 0:
            continue

        # 2) Формируем вектор u.
        # Знак выбираем противоположный x[0] для численной устойчивости
        sign_x0 = 1.0 if x[0] >= 0 else -1.0
        u = x.copy()
        u[0] += sign_x0 * norm_x

        # 3) Нормируем вектор u
        norm_u = np.linalg.norm(u)
        if norm_u == 0:
            continue
        u = u / norm_u

        # 4) Строим матрицу Хаусхолдера H' для текущего подпространства
        # H' = E - 2 * u * u^T
        size_H_prime = n - k - 1
        H_prime = np.eye(size_H_prime) - 2.0 * np.outer(u, u)

        # 5) Строим блочную матрицу H для всей матрицы A
        H = np.eye(n)
        # Вставляем H' в правый нижний блок
        # --- ВОССТАНОВЛЕНО ПО СТАНДАРТНОЙ СХЕМЕ (этих строк не было видно на скриншоте) ---
        H[k + 1:, k + 1:] = H_prime

        # 6) Применяем преобразование подобия: A = H * A * H
        A = H @ A @ H

        # 7) Накапливаем матрицу преобразований Q (итоговая Q: A_tri = Q^T * A_orig * Q)
        Q = Q @ H
        # --- КОНЕЦ ВОССТАНОВЛЕННОГО УЧАСТКА ---

    return A, Q


# ========================================
# Пример использования
# ========================================
if __name__ == "__main__":
    A_orig = np.array([
        [4.0, 1.0, -2.0, 2.0],
        [1.0, 2.0, 0.0, 1.0],
        [-2.0, 0.0, -3.0, -1.0],
        [2.0, 1.0, -1.0, 2.0]
    ])

    print("Исходная матрица A:")
    print(A_orig)

    A_tri, Q = tridiagonalize_householder(A_orig)

    print("\nТрехдиагональная матрица:")
    print(A_tri)

    # Проверка: собственные значения исходной и полученной матриц должны совпадать
    print("\nСобственные значения исходной A:", np.linalg.eigvalsh(A_orig))
    print("Собственные значения трехдиагональной:", np.linalg.eigvalsh(A_tri))
